#!/usr/bin/env node
// Generates the shared bridge secret and writes it to server/.bridge-token and
// extension/config.local.js (both gitignored). Re-running is a no-op unless --rotate is passed.
import { randomBytes } from 'node:crypto';
import { chmodSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOKEN_FILE = path.join(ROOT, 'server', '.bridge-token');
const CONFIG_FILE = path.join(ROOT, 'extension', 'config.local.js');
const PORT = 17373;

function readOrNull(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

const rotate = process.argv.includes('--rotate');
const existing = readOrNull(TOKEN_FILE)?.trim();
const config = readOrNull(CONFIG_FILE);

if (!rotate && existing && /^[0-9a-f]{64}$/.test(existing) && config?.includes(existing)) {
  console.log('Bridge token already initialised (server/.bridge-token matches extension/config.local.js).');
  console.log('Pass --rotate to generate a new one.');
  process.exit(0);
}

const token = randomBytes(32).toString('hex');
writeFileSync(TOKEN_FILE, `${token}\n`, { mode: 0o600 });
chmodSync(TOKEN_FILE, 0o600);
writeFileSync(
  CONFIG_FILE,
  `// Generated by scripts/init-token.mjs — local secret, never commit (gitignored).\n` +
    `self.MCP_BRIDGE_CONFIG = ${JSON.stringify({ token, port: PORT }, null, 2)};\n`,
  { mode: 0o600 },
);
chmodSync(CONFIG_FILE, 0o600);

console.log(`Wrote ${path.relative(ROOT, TOKEN_FILE)} and ${path.relative(ROOT, CONFIG_FILE)} (32-byte random token).`);
if (existing) {
  console.log('Token rotated: reload the extension in chrome://extensions and restart the MCP server (/mcp in Claude Code).');
}
